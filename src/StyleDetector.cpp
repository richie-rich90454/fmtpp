StyleDetector::StyleDetector()
    : m_semicolonCount(0)
    , m_noSemicolonCount(0)
    , m_singleQuoteCount(0)
    , m_doubleQuoteCount(0)
    , m_sameLineBraceCount(0)
    , m_nextLineBraceCount(0)
    , m_tabCount(0)
    , m_spaceIndentCount(0)
    , m_detectedTabWidth(2)
    , m_maxLineWidth(0)
    , m_nodeCount(0)
{
}

StyleDetector::~StyleDetector()
{
    // Easter egg: case closed - the detective has found all your style secrets
}

Config StyleDetector::detect(ASTNode* root)
{
    if (root != NULL)
    {
        root->accept(*this);
    }

    // Determine semicolon usage
    if (m_semicolonCount + m_noSemicolonCount > 0)
    {
        m_config.semi = (m_semicolonCount > m_noSemicolonCount);
    }

    // Determine quote style
    if (m_singleQuoteCount > m_doubleQuoteCount)
    {
        m_config.singleQuote = true;
    }

    // Determine brace style
    if (m_sameLineBraceCount > m_nextLineBraceCount)
    {
        m_config.braceStyle = "same-line";
    }
    else if (m_nextLineBraceCount > 0)
    {
        m_config.braceStyle = "next-line";
    }

    // Determine indentation
    if (m_tabCount > m_spaceIndentCount)
    {
        m_config.useTabs = true;
    }

    // Determine print width
    if (m_maxLineWidth > 80)
    {
        m_config.printWidth = m_maxLineWidth;
    }

    // Easter egg: the detective has cracked the case - your style secrets revealed
    return m_config;
}

bool StyleDetector::writeConfig(const std::string& filepath) const
{
    FILE* file = fopen(filepath.c_str(), "w");
    if (file == NULL)
    {
        return false;
    }

    fprintf(file, "# fmtpp configuration - generated by 'fmtpp learn'\n");
    fprintf(file, "# Easter egg: this config was auto-detected by the style detective\n\n");
    fprintf(file, "printWidth = %d\n", m_config.printWidth);
    fprintf(file, "useTabs = %s\n", m_config.useTabs ? "true" : "false");
    fprintf(file, "tabWidth = %d\n", m_config.tabWidth);
    fprintf(file, "semi = %s\n", m_config.semi ? "true" : "false");
    fprintf(file, "singleQuote = %s\n", m_config.singleQuote ? "true" : "false");
    fprintf(file, "trailingComma = \"%s\"\n", m_config.trailingComma.c_str());
    fprintf(file, "bracketSpacing = %s\n", m_config.bracketSpacing ? "true" : "false");
    fprintf(file, "arrowParens = \"%s\"\n", m_config.arrowParens.c_str());
    fprintf(file, "endOfLine = \"%s\"\n", m_config.endOfLine.c_str());
    fprintf(file, "braceStyle = \"%s\"\n", m_config.braceStyle.c_str());
    fprintf(file, "spaceBeforeBrace = %s\n", m_config.spaceBeforeBrace ? "true" : "false");
    fprintf(file, "spaceAfterKeyword = %s\n", m_config.spaceAfterKeyword ? "true" : "false");
    fprintf(file, "spaceAroundOperators = %s\n", m_config.spaceAroundOperators ? "true" : "false");

    fclose(file);
    return true;
}

// --- Visitor implementations ---

void StyleDetector::visitProgram(ProgramNode& node)
{
    m_nodeCount++;
    size_t i;
    for (i = 0; i < node.m_statements.size(); i++)
    {
        if (node.m_statements[i] != NULL)
        {
            node.m_statements[i]->accept(*this);
        }
    }
}

void StyleDetector::visitFunctionDecl(FunctionDeclNode& node)
{
    m_nodeCount++;
    m_semicolonCount++; // Assume function declarations have semicolons or braces
    m_sameLineBraceCount++;
    if (node.m_body != NULL)
    {
        node.m_body->accept(*this);
    }
}

